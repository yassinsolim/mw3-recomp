#!/system/bin/sh
# A title's game library, built on the phone from its executable, with the
# toolchain package alone: what the app's own build does (docs/ondevice-build.md),
# as a script, to try the toolchain on a device and to time it. Run by the
# probe app (android/toolchain-probe), or from an adb shell with the same
# variables set.
#
#   sh device_build.sh <input folder> <output folder> [jobs] [optimisation]
#   Environment: TOOLS (the toolchain's programs), DATA (its data.zip, unpacked)
#   Input, pushed by tools/toolchain/device_test.py:
#     title.env            LIBRARY, TOML, TABLES, PPC, XEX and DEFINES of the title
#     abi_fixed.txt        the statement's lines that are the checkout's: the
#                          recompiler, its patch, the configuration, the script
#                          that writes the shared header
#     abi_hook.txt         its last line, of runtime/mmio_hook.h
#     config/<TOML>, <XEX>, runtime/mmio_hook.h, cmake/game_library.list
#   Output: lib<LIBRARY>game.so, game_abi.cpp, build.txt (times and memory)
# toolchain.json is the reference for the command lines; these are its, and
# device_test.py checks that they still are.
set -eu
IN=$1
OUT=$2
JOBS=${3:-8}
OPT=${4:--O2}
. "$IN/title.env"
LLVM=$TOOLS/libllvm.so
mkdir -p "$OUT/config" "$OUT/obj" "$OUT/XenonRecomp/XenonUtils"
now() { date +%s; }

# The recompiler reads its configuration's paths from the folder it runs in,
# as on the PC: config/ beside the executable's folder and the tree's.
cp "$IN/config/$TOML" "$OUT/config/"
mkdir -p "$OUT/$(dirname "$XEX")"
cp "$IN/$XEX" "$OUT/$XEX"
cp "$DATA/XenonRecomp/XenonUtils/ppc_context.h" "$OUT/XenonRecomp/XenonUtils/"
cd "$OUT"
T0=$(now)
"$TOOLS/libXenonAnalyse.so" "$XEX" "config/$TABLES" >analyse.log 2>&1
rm -rf "$PPC" && mkdir "$PPC"
(cd config && "$TOOLS/libXenonRecomp.so" "$TOML" ../XenonRecomp/XenonUtils/ppc_context.h) >recomp.log 2>&1
T1=$(now)

# tools/genshared.py: every function the tree defines or calls, declared in
# one header, and the system calls among them listed.
NAME='[A-Za-z_][A-Za-z0-9_]*'
cat "$PPC"/ppc_recomp.*.cpp "$PPC/ppc_func_mapping.cpp" >all.cpp
grep -o -E "(PPC_FUNC_IMPL|PPC_WEAK_FUNC)\($NAME\)" all.cpp | sed -E 's/^[A-Z_]+\((.*)\)$/\1/' | LC_ALL=C sort -u >defs.txt
{
    grep -o -E "$NAME\(ctx, base\)" all.cpp | sed 's/(ctx, base)$//'
    grep -o -E "\{ 0x[0-9A-F]+, $NAME \}" all.cpp | sed -E 's/^.*, (.*) \}$/\1/'
} | grep -v -x PPC_CALL_INDIRECT_FUNC | LC_ALL=C sort -u >refs.txt
rm all.cpp
{
    cat "$IN/shared_header_prefix.h"
    cat defs.txt refs.txt | LC_ALL=C sort -u | sed 's/^\(.*\)$/PPC_FUNC(\1);/'
    echo "}"
} >"$PPC/ppc_recomp_shared.h"
LC_ALL=C comm -13 defs.txt refs.txt | grep '^__imp__' | sed 's/^__imp__//' >"$PPC/kernel_imports.txt"
T2=$(now)

# cmake/game_abi.cmake: the statement, a line for each thing the library was
# built against, of the files as they are here.
# (Not "hash": the phone's shell has a command of that name.)
abi_hash() { tr -d '\r' <"$1" | sha256sum | cut -d' ' -f1; }
{
    echo "title $LIBRARY"
    cat "$IN/abi_fixed.txt"
    echo "jump-tables $(abi_hash "config/$TABLES")"
    echo "code-extent $(abi_hash "$PPC/ppc_config.h")"
    echo "register-context $(abi_hash "$PPC/ppc_context.h")"
    echo "system-calls $(abi_hash "$PPC/kernel_imports.txt")"
    cat "$IN/abi_hook.txt"
} >game_abi.txt
{
    echo '// Generated by tools/toolchain/device_build.sh, as cmake/game_abi.cmake writes it.'
    printf 'extern "C" __attribute__((visibility("default"))) const char mw2_game_abi[] = R"abi('
    cat game_abi.txt
    echo ')abi";'
} >game_abi.cpp

# What the phone has free and what the compilers hold, a sample a second.
(
    LOW=999999999; PEAK=0; ONE=0
    while [ ! -e "$OUT/done" ]; do
        FREE=$(grep MemAvailable /proc/meminfo | tr -s ' ' | cut -d' ' -f2)
        [ "$FREE" -lt "$LOW" ] && LOW=$FREE
        SUM=0
        for RSS in $(ps -A -o RSS,NAME | grep libllvm.so | tr -s ' ' | sed 's/^ //' | cut -d' ' -f1); do
            SUM=$((SUM + RSS))
            [ "$RSS" -gt "$ONE" ] && ONE=$RSS
        done
        [ "$SUM" -gt "$PEAK" ] && PEAK=$SUM
        echo "least-available-kB $LOW compilers-peak-kB $PEAK one-compiler-peak-kB $ONE" >"$OUT/memory.txt"
        sleep 1
    done
) &

COMPILE="$LLVM clang --driver-mode=g++ --target=aarch64-none-linux-android26 --sysroot=$DATA/sysroot -resource-dir $DATA/lib/clang/19 -DANDROID -fdata-sections -ffunction-sections -funwind-tables -fstack-protector-strong -no-canonical-prefixes -D_FORTIFY_SOURCE=2 -Wformat -Werror=format-security $OPT -DNDEBUG -fPIC -w -fwrapv -include $IN/runtime/mmio_hook.h -fno-omit-frame-pointer -std=gnu++20 $DEFINES -Dppc_recomp_EXPORTS -I$PPC -I$DATA/XenonRecomp/thirdparty/simde -I$DATA/XenonRecomp/thirdparty/simde/simde"
# The largest files first: the last compiles are then short ones, and all the
# cores are busy to the end.
ls -S "$PPC"/ppc_recomp.*.cpp "$PPC/ppc_func_mapping.cpp" game_abi.cpp >sources.txt
xargs -P "$JOBS" -n 1 sh -c "$COMPILE -c \$0 -o obj/\$(basename \$0).o || exit 255" <sources.txt
T3=$(now)
ls obj/*.o >objects.rsp
LIB=$DATA/sysroot/usr/lib/aarch64-linux-android
RT=$DATA/lib/clang/19/lib/linux
# link <library> <objects and options>
link() {
    LIBRARY_FILE=$1
    shift
    "$LLVM" ld.lld --sysroot="$DATA/sysroot" -EL --fix-cortex-a53-843419 -z now -z relro -z max-page-size=16384 \
        --hash-style=gnu --eh-frame-hdr -m aarch64linux -shared "$LIB/26/crtbegin_so.o" \
        "-L$RT/aarch64" "-L$LIB/26" "-L$LIB" "-L$DATA/sysroot/usr/lib" \
        --no-rosegment --no-undefined-version --fatal-warnings --no-undefined \
        --build-id=sha1 --gc-sections -z max-page-size=16384 -z common-page-size=16384 \
        -soname "$LIBRARY_FILE" -o "$LIBRARY_FILE" "$@" \
        -latomic -lm -Bstatic -lc++ -Bdynamic -lm \
        "$RT/libclang_rt.builtins-aarch64-android.a" -l:libunwind.a -ldl -lc \
        "$RT/libclang_rt.builtins-aarch64-android.a" -l:libunwind.a -ldl "$LIB/26/crtend_so.o"
}
link "lib${LIBRARY}game.so" "--dynamic-list=$IN/cmake/game_library.list" --unresolved-symbols=ignore-all @objects.rsp
T4=$(now)
# A library of one function, compiled and linked as the game's is, for the
# probe app to load: the game's own loads only into the runtime it calls.
echo 'extern "C" int toolchain_probe() { return 1; }' >probe.cpp
$COMPILE -c probe.cpp -o probe.o
link libtoolchainprobe.so probe.o
touch done
wait
{
    echo "recompile-seconds $((T1 - T0))"
    echo "shared-header-seconds $((T2 - T1))"
    echo "compile-seconds $((T3 - T2)) jobs $JOBS $OPT"
    echo "link-seconds $((T4 - T3))"
    cat memory.txt
    ls -l "lib${LIBRARY}game.so"
} >build.txt
cat build.txt
